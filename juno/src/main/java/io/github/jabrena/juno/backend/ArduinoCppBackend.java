    /**
     * Converts a pointer expression to the {@code int32_t} handle representation every array reference is
     * stored as. {@code reinterpret_cast<int32_t>(pointer)} is only valid when a pointer fits in 32 bits —
     * true on the actual Cortex-M4 target, but not on a 64-bit host, where syntax checks (and any other
     * non-target compilation) would reject it. Going through {@code intptr_t} first is valid on both: exact
     * on the 32-bit target, and merely truncating (never executed there) on a 64-bit host.
     */
    private String handleOf(String pointerExpression) {
        return "static_cast<int32_t>(reinterpret_cast<intptr_t>(" + pointerExpression + "))";
    }

    private String prototype(IrMethod method) {
        Descriptor descriptor = Descriptor.parse(method.reference().descriptor());
        String returnType;
        if (descriptor.returnsVoid()) {
            returnType = "void";
        } else if (Descriptor.isLong(descriptor.returnType())) {
            returnType = "int64_t";
        } else if (Descriptor.isFloat(descriptor.returnType())) {
            returnType = "float";
        } else if (Descriptor.isDouble(descriptor.returnType())) {
            returnType = "double";
        } else {
            Optional<ArrayElementType> arrayReturn = arrayElementTypeOf(descriptor.returnType());
            returnType = arrayReturn.map(type -> cppType(type) + "*").orElse("int32_t");
        }
        StringBuilder result = new StringBuilder("static ").append(returnType).append(' ')
                .append(CppNames.method(method.reference())).append('(');
        boolean hasParameter = false;
        if (!method.isStatic()) {
            result.append("int32_t arg_receiver");
            hasParameter = true;
        }
        List<String> parameterTypes = descriptor.parameters();
        for (int i = 0; i < parameterTypes.size(); i++) {
            if (hasParameter) {
                result.append(", ");
            }
            String parameterType = parameterTypes.get(i);
            Optional<ArrayElementType> arrayParam = arrayElementTypeOf(parameterType);
            String cppParameter = Descriptor.isLong(parameterType)
                    ? "int64_t arg"
                    : Descriptor.isDouble(parameterType)
                    ? "double arg"
                    : Descriptor.isFloat(parameterType)
                            ? "float arg"
                            : arrayParam.map(type -> cppType(type) + "* arg").orElse("int32_t arg");
            result.append(cppParameter).append(i);
            hasParameter = true;
        }
        return result.append(')').toString();
    }

    private Optional<ArrayElementType> arrayElementTypeOf(String type) {
        if (!Descriptor.isArrayType(type)) {
            return Optional.empty();
        }
        return ArrayElementType.fromArrayDescriptor(type);
    }

    private String cppType(ArrayElementType elementType) {
        return switch (elementType) {
            case BYTE -> "int8_t";
            case CHAR -> "uint16_t";
            case SHORT -> "int16_t";
            case INT -> "int32_t";
            case REFERENCE -> "int32_t";
            case LONG -> "int64_t";
            case FLOAT -> "float";
            case DOUBLE -> "double";
        };
    }

