package io.github.jabrena.juno.backend;

import io.github.jabrena.juno.CompileException;
import io.github.jabrena.juno.bytecode.Instruction;
import io.github.jabrena.juno.classfile.MethodRef;
import io.github.jabrena.juno.linker.Descriptor;
import io.github.jabrena.juno.linker.Intrinsics;
import io.github.jabrena.juno.linker.LinkedMethod;
import io.github.jabrena.juno.linker.Program;

/** Emits portable Arduino C++ which the Renesas core compiles to Cortex-M4 machine code. */
public final class ArduinoCppBackend {
    private static final String LED_MATRIX_OWNER = "io/github/jabrena/juno/api/LedMatrix";
    private static final String MOUSE_OWNER = "io/github/jabrena/juno/api/Mouse";

    public String generate(Program program) {
        boolean usesLedMatrix = usesOwner(program, LED_MATRIX_OWNER);
        boolean usesMouse = usesOwner(program, MOUSE_OWNER);
        StringBuilder output = new StringBuilder();
        output.append("// Generated by Juno. Do not edit.\n")
                .append("// Closed-world entry point: ").append(program.entryPoint().displayName()).append("\n")
                .append("#include <Arduino.h>\n")
                .append("#include <stdint.h>\n");
        if (usesLedMatrix) {
            output.append("#include \"Arduino_LED_Matrix.h\"\n");
        }
        if (usesMouse) {
            output.append("#include <Mouse.h>\n");
        }
        output.append('\n').append(runtimeHelpers());
        if (usesLedMatrix) {
            output.append(ledMatrixHelpers());
        }

        for (LinkedMethod linked : program.methods()) {
            output.append(prototype(linked.method().reference())).append(";\n");
        }
        output.append('\n');
        for (LinkedMethod linked : program.methods()) {
            emitMethod(output, linked);
        }

        Descriptor entryDescriptor = Descriptor.parse(program.entryPoint().descriptor());
        output.append("void setup() {\n  ")
                .append(CppNames.method(program.entryPoint())).append('(');
        if (!entryDescriptor.parameters().isEmpty()) {
            output.append('0'); // closed-world programs have no command-line arguments
        }
        output.append(");\n}\n\nvoid loop() {\n}\n");
        return output.toString();
    }

    private boolean usesOwner(Program program, String owner) {
        for (LinkedMethod linked : program.methods()) {
            for (Instruction instruction : linked.instructions()) {
                if (instruction.opcode() == 182 || instruction.opcode() == 184) {
                    MethodRef called = linked.owner().constantPool().methodRef(instruction.operandA());
                    if (called.owner().equals(owner)) {
                        return true;
                    }
                }
            }
        }
        return false;
    }

    private void emitMethod(StringBuilder output, LinkedMethod linked) {
        Descriptor descriptor = Descriptor.parse(linked.method().descriptor());
        output.append(prototype(linked.method().reference())).append(" {\n")
                .append("  int32_t locals[").append(Math.max(1, linked.method().maxLocals())).append("] = {};\n")
                .append("  int32_t stack[").append(Math.max(1, linked.method().maxStack())).append("] = {};\n")
                .append("  uint16_t sp = 0;\n");
        for (int index = 0; index < descriptor.parameters().size(); index++) {
            output.append("  locals[").append(index).append("] = arg").append(index).append(";\n");
        }
        for (Instruction instruction : linked.instructions()) {
            emitInstruction(output, linked, instruction);
        }
        if (descriptor.returnsVoid()) {
            output.append("  return;\n");
        } else {
            output.append("  juno_panic();\n  return 0;\n");
        }
        output.append("}\n\n");
    }

    private void emitInstruction(StringBuilder output, LinkedMethod linked, Instruction instruction) {
        int opcode = instruction.opcode();
        output.append("juno_pc_").append(instruction.offset()).append(":\n");
        switch (opcode) {
            case 0 -> output.append("  ;\n");
            case 2 -> push(output, "-1");
            case 3, 4, 5, 6, 7, 8 -> push(output, Integer.toString(opcode - 3));
            case 16, 17 -> push(output, Integer.toString(instruction.operandA()));
            case 18, 19 -> push(output,
                    Integer.toString(linked.owner().constantPool().integer(instruction.operandA())));
            case 21, 25 -> push(output, "locals[" + instruction.operandA() + "]");
            case 26, 27, 28, 29 -> push(output, "locals[" + (opcode - 26) + "]");
            case 42, 43, 44, 45 -> push(output, "locals[" + (opcode - 42) + "]");
            case 54, 58 -> store(output, instruction.operandA());
            case 59, 60, 61, 62 -> store(output, opcode - 59);
            case 75, 76, 77, 78 -> store(output, opcode - 75);
            case 87 -> output.append("  --sp;\n");
            case 89 -> output.append("  stack[sp] = stack[sp - 1]; ++sp;\n");
            case 96 -> binary(output, "juno_iadd");
            case 100 -> binary(output, "juno_isub");
            case 104 -> binary(output, "juno_imul");
            case 108 -> binary(output, "juno_idiv");
            case 112 -> binary(output, "juno_irem");
            case 116 -> output.append("  stack[sp - 1] = juno_ineg(stack[sp - 1]);\n");
            case 120 -> binary(output, "juno_ishl");
            case 122 -> binary(output, "juno_ishr");
            case 124 -> binary(output, "juno_iushr");
            case 126 -> binary(output, "juno_iand");
            case 128 -> binary(output, "juno_ior");
            case 130 -> binary(output, "juno_ixor");
            case 132 -> output.append("  locals[").append(instruction.operandA()).append("] = juno_iadd(locals[")
                    .append(instruction.operandA()).append("], ").append(instruction.operandB()).append(");\n");
            case 145 -> output.append("  stack[sp - 1] = juno_i2b(stack[sp - 1]);\n");
            case 146 -> output.append("  stack[sp - 1] = static_cast<uint16_t>(stack[sp - 1]);\n");
            case 147 -> output.append("  stack[sp - 1] = juno_i2s(stack[sp - 1]);\n");
            case 153, 154, 155, 156, 157, 158 -> emitUnaryBranch(output, instruction);
            case 159, 160, 161, 162, 163, 164 -> emitBinaryBranch(output, instruction);
            case 167 -> output.append("  goto juno_pc_")
                    .append(instruction.offset() + instruction.operandA()).append(";\n");
            case 172 -> output.append("  return stack[--sp];\n");
            case 177 -> output.append("  return;\n");
            case 182, 184 -> emitCall(output, linked, instruction);
            default -> throw new IllegalStateException("Decoder admitted unsupported opcode " + opcode);
        }
    }

    private void emitCall(StringBuilder output, LinkedMethod linked, Instruction instruction) {
        MethodRef called = linked.owner().constantPool().methodRef(instruction.operandA());
        Descriptor descriptor = Descriptor.parse(called.descriptor());
        output.append("  {\n");
        for (int index = descriptor.parameters().size() - 1; index >= 0; index--) {
            output.append("    int32_t call_arg").append(index).append(" = stack[--sp];\n");
        }
        if (instruction.opcode() == 182) {
            output.append("    int32_t call_receiver = stack[--sp];\n");
        }
        output.append("    ");
        if (!descriptor.returnsVoid()) {
            output.append("stack[sp++] = ");
        }
        if (Intrinsics.contains(called)) {
            output.append(intrinsicExpression(called));
        } else {
            output.append(CppNames.method(called)).append('(').append(arguments(descriptor.parameters().size())).append(')');
        }
        output.append(";\n  }\n");
    }

    private String intrinsicExpression(MethodRef method) {
        String key = method.owner() + "." + method.name() + method.descriptor();
        return switch (key) {
            case "io/github/jabrena/juno/api/Gpio.pinMode(II)V" -> "pinMode(call_arg0, call_arg1)";
            case "io/github/jabrena/juno/api/Gpio.digitalWrite(IZ)V" ->
                    "digitalWrite(call_arg0, call_arg1 ? HIGH : LOW)";
            case "io/github/jabrena/juno/api/Gpio.digitalRead(I)Z" ->
                    "static_cast<int32_t>(digitalRead(call_arg0) == HIGH)";
            case "io/github/jabrena/juno/api/Gpio.analogRead(I)I" -> "static_cast<int32_t>(analogRead(call_arg0))";
            case "io/github/jabrena/juno/api/Gpio.analogWrite(II)V" -> "analogWrite(call_arg0, call_arg1)";
            case "io/github/jabrena/juno/api/Gpio.toggle(I)V" ->
                    "digitalWrite(call_arg0, digitalRead(call_arg0) == HIGH ? LOW : HIGH)";
            case "io/github/jabrena/juno/api/Delay.millis(I)V" -> "delay(static_cast<unsigned long>(call_arg0))";
            case "io/github/jabrena/juno/api/Delay.micros(I)V" -> "delayMicroseconds(static_cast<unsigned int>(call_arg0))";
            case "io/github/jabrena/juno/api/Clock.millis()I" -> "static_cast<int32_t>(millis())";
            case "io/github/jabrena/juno/api/Clock.micros()I" -> "static_cast<int32_t>(micros())";
            case "io/github/jabrena/juno/api/DigitalOutput.of(I)Lio/github/jabrena/juno/api/DigitalOutput;" ->
                    "juno_digital_output_of(call_arg0)";
            case "io/github/jabrena/juno/api/DigitalOutput.high()V" ->
                    "digitalWrite(call_receiver, HIGH)";
            case "io/github/jabrena/juno/api/DigitalOutput.low()V" ->
                    "digitalWrite(call_receiver, LOW)";
            case "io/github/jabrena/juno/api/DigitalOutput.toggle()V" ->
                    "digitalWrite(call_receiver, digitalRead(call_receiver) == HIGH ? LOW : HIGH)";
            case "io/github/jabrena/juno/api/DigitalOutput.isHigh()Z" ->
                    "static_cast<int32_t>(digitalRead(call_receiver) == HIGH)";
            case "io/github/jabrena/juno/api/LedMatrix.begin()V" -> "juno_led_matrix_begin()";
            case "io/github/jabrena/juno/api/LedMatrix.loadFrame(III)V" ->
                    "juno_led_matrix_load_frame(call_arg0, call_arg1, call_arg2)";
            case "io/github/jabrena/juno/api/LedMatrix.clear()V" -> "juno_led_matrix_clear()";
            case "io/github/jabrena/juno/api/Serial.begin(I)V" ->
                    "Serial.begin(static_cast<unsigned long>(call_arg0))";
            case "io/github/jabrena/juno/api/Serial.print(I)V" -> "Serial.print(call_arg0)";
            case "io/github/jabrena/juno/api/Serial.println(I)V" -> "Serial.println(call_arg0)";
            case "io/github/jabrena/juno/api/Mouse.begin()V" -> "Mouse.begin()";
            case "io/github/jabrena/juno/api/Mouse.move(II)V" ->
                    "Mouse.move(static_cast<signed char>(call_arg0), static_cast<signed char>(call_arg1))";
            default -> throw new CompileException("Missing C++ lowering for intrinsic " + method.displayName());
        };
    }

    private void emitUnaryBranch(StringBuilder output, Instruction instruction) {
        String operator = switch (instruction.opcode()) {
            case 153 -> "==";
            case 154 -> "!=";
            case 155 -> "<";
            case 156 -> ">=";
            case 157 -> ">";
            case 158 -> "<=";
            default -> throw new IllegalStateException();
        };
        output.append("  if (stack[--sp] ").append(operator).append(" 0) goto juno_pc_")
                .append(instruction.offset() + instruction.operandA()).append(";\n");
    }

    private void emitBinaryBranch(StringBuilder output, Instruction instruction) {
        String operator = switch (instruction.opcode()) {
            case 159 -> "==";
            case 160 -> "!=";
            case 161 -> "<";
            case 162 -> ">=";
            case 163 -> ">";
            case 164 -> "<=";
            default -> throw new IllegalStateException();
        };
        output.append("  { int32_t rhs = stack[--sp]; int32_t lhs = stack[--sp]; if (lhs ")
                .append(operator).append(" rhs) goto juno_pc_")
                .append(instruction.offset() + instruction.operandA()).append("; }\n");
    }

    private void push(StringBuilder output, String expression) {
        output.append("  stack[sp++] = ").append(expression).append(";\n");
    }

    private void store(StringBuilder output, int local) {
        output.append("  locals[").append(local).append("] = stack[--sp];\n");
    }

    private void binary(StringBuilder output, String helper) {
        output.append("  { int32_t rhs = stack[--sp]; int32_t lhs = stack[--sp]; stack[sp++] = ")
                .append(helper).append("(lhs, rhs); }\n");
    }

    private String prototype(MethodRef method) {
        Descriptor descriptor = Descriptor.parse(method.descriptor());
        String returnType = descriptor.returnsVoid() ? "void" : "int32_t";
        StringBuilder result = new StringBuilder("static ").append(returnType).append(' ')
                .append(CppNames.method(method)).append('(');
        for (int i = 0; i < descriptor.parameters().size(); i++) {
            if (i > 0) {
                result.append(", ");
            }
            result.append("int32_t arg").append(i);
        }
        return result.append(')').toString();
    }

    private String arguments(int count) {
        StringBuilder result = new StringBuilder();
        for (int i = 0; i < count; i++) {
            if (i > 0) {
                result.append(", ");
            }
            result.append("call_arg").append(i);
        }
        return result.toString();
    }

    private String runtimeHelpers() {
        return """
                [[noreturn]] static void juno_panic() {
                  noInterrupts();
                  for (;;) {}
                }

                static int32_t juno_iadd(int32_t a, int32_t b) {
                  return static_cast<int32_t>(static_cast<uint32_t>(a) + static_cast<uint32_t>(b));
                }
                static int32_t juno_isub(int32_t a, int32_t b) {
                  return static_cast<int32_t>(static_cast<uint32_t>(a) - static_cast<uint32_t>(b));
                }
                static int32_t juno_imul(int32_t a, int32_t b) {
                  return static_cast<int32_t>(static_cast<uint32_t>(a) * static_cast<uint32_t>(b));
                }
                static int32_t juno_idiv(int32_t a, int32_t b) {
                  if (b == 0) juno_panic();
                  if (a == INT32_MIN && b == -1) return INT32_MIN;
                  return a / b;
                }
                static int32_t juno_irem(int32_t a, int32_t b) {
                  if (b == 0) juno_panic();
                  if (a == INT32_MIN && b == -1) return 0;
                  return a % b;
                }
                static int32_t juno_ineg(int32_t value) {
                  return static_cast<int32_t>(0u - static_cast<uint32_t>(value));
                }
                static int32_t juno_ishl(int32_t a, int32_t b) {
                  return static_cast<int32_t>(static_cast<uint32_t>(a) << (b & 31));
                }
                static int32_t juno_ishr(int32_t a, int32_t b) {
                  uint32_t shift = static_cast<uint32_t>(b) & 31u;
                  uint32_t value = static_cast<uint32_t>(a);
                  if (shift == 0 || a >= 0) return static_cast<int32_t>(value >> shift);
                  return static_cast<int32_t>((value >> shift) | (~0u << (32u - shift)));
                }
                static int32_t juno_iushr(int32_t a, int32_t b) {
                  return static_cast<int32_t>(static_cast<uint32_t>(a) >> (b & 31));
                }
                static int32_t juno_iand(int32_t a, int32_t b) { return a & b; }
                static int32_t juno_ior(int32_t a, int32_t b) { return a | b; }
                static int32_t juno_ixor(int32_t a, int32_t b) { return a ^ b; }
                static int32_t juno_i2b(int32_t value) {
                  uint32_t narrowed = static_cast<uint32_t>(value) & 0xffu;
                  return static_cast<int32_t>(narrowed >= 0x80u ? narrowed | 0xffffff00u : narrowed);
                }
                static int32_t juno_i2s(int32_t value) {
                  uint32_t narrowed = static_cast<uint32_t>(value) & 0xffffu;
                  return static_cast<int32_t>(narrowed >= 0x8000u ? narrowed | 0xffff0000u : narrowed);
                }
                static int32_t juno_digital_output_of(int32_t pin) {
                  pinMode(pin, OUTPUT);
                  return pin;
                }

                """;
    }

    private String ledMatrixHelpers() {
        return """
                ArduinoLEDMatrix juno_led_matrix;
                static void juno_led_matrix_begin() {
                  juno_led_matrix.begin();
                }
                static void juno_led_matrix_load_frame(int32_t word0, int32_t word1, int32_t word2) {
                  const uint32_t frame[3] = {
                    static_cast<uint32_t>(word0),
                    static_cast<uint32_t>(word1),
                    static_cast<uint32_t>(word2)
                  };
                  juno_led_matrix.loadFrame(frame);
                }
                static void juno_led_matrix_clear() {
                  const uint32_t frame[3] = {0, 0, 0};
                  juno_led_matrix.loadFrame(frame);
                }

                """;
    }
}
