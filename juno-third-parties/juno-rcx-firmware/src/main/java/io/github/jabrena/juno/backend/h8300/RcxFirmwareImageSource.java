package io.github.jabrena.juno.backend.h8300;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Objects;

/** Generates the flash-resident Java representation used by the Arduino-side RCX firmware downloader. */
public final class RcxFirmwareImageSource {
    private static final int IMAGE_START = 0x8000;
    private static final int IMAGE_MAX_LENGTH = 0x7000;
    private static final int CHECKSUM_END = 0xCC00;
    private static final int CHUNK_SIZE = 4096;
    private static final String PACKAGE = "io.github.jabrena.juno.thirdparty.lego.rcxfirmware";

    private final H8Image image;
    private final byte[] bytes;

    public RcxFirmwareImageSource(H8Image image) {
        this.image = image;
        this.bytes = image.bytes();
        if (image.origin() != IMAGE_START) {
            throw new FirmwareGenerationException(
                    "RCX firmware must start at 0x8000, not 0x%04X".formatted(image.origin()));
        }
        if (bytes.length == 0 || bytes.length > IMAGE_MAX_LENGTH) {
            throw new FirmwareGenerationException("RCX firmware length must be 1 to 28672 bytes, not " + bytes.length);
        }
        if (image.entry() < IMAGE_START || image.entry() >= IMAGE_START + bytes.length) {
            throw new FirmwareGenerationException(
                    "RCX firmware entry is outside the image: 0x%04X".formatted(image.entry()));
        }
    }

    /** Writes the generated Java source, creating its parent directories when needed. */
    public void write(Path output) throws IOException {
        Path absolute = output.toAbsolutePath();
        Files.createDirectories(Objects.requireNonNull(absolute.getParent(), "output has no parent directory"));
        Files.writeString(absolute, source(), StandardCharsets.UTF_8);
        System.out.printf("Wrote %s: %d firmware bytes, checksum 0x%04X%n", output, bytes.length, checksum());
    }

    String source() {
        int chunks = (bytes.length + CHUNK_SIZE - 1) / CHUNK_SIZE;
        StringBuilder cases = new StringBuilder();
        StringBuilder classes = new StringBuilder();
        for (int chunk = 0; chunk < chunks; chunk++) {
            cases.append("            case ").append(chunk).append(" -> Chunk").append(chunk)
                    .append(".DATA[offset];\n");
            classes.append(chunkSource(chunk));
        }
        return """
                package %s;

                /** Generated by RcxRemoteFirmware from the same image as firmware.srec; do not edit by hand. */
                public final class RcxFirmwareImage {
                    public static final int ORIGIN = 0x%04X;
                    public static final int LENGTH = %d;
                    public static final int ENTRY = 0x%04X;
                    public static final int CHECKSUM = 0x%04X;
                    private static final int CHUNK_SIZE = %d;

                    private RcxFirmwareImage() {
                    }

                    public static byte byteAt(int address) {
                        int offset = address %% CHUNK_SIZE;
                        return switch (address / CHUNK_SIZE) {
                %s            default -> 0;
                        };
                    }
                %s}
                """.formatted(PACKAGE, image.origin(), bytes.length, image.entry(), checksum(), CHUNK_SIZE, cases,
                classes);
    }

    private String chunkSource(int chunk) {
        int from = chunk * CHUNK_SIZE;
        int to = Math.min(bytes.length, from + CHUNK_SIZE);
        StringBuilder values = new StringBuilder();
        for (int i = from; i < to; i++) {
            values.append((i - from) % 16 == 0 ? "\n                " : " ").append(bytes[i]).append(',');
        }
        return """

                    private static final class Chunk%d {
                        private static final byte[] DATA = {%s
                        };
                    }
                """.formatted(chunk, values);
    }

    private int checksum() {
        int covered = Math.min(bytes.length, CHECKSUM_END - image.origin());
        int sum = 0;
        for (int i = 0; i < covered; i++) {
            sum += bytes[i] & 0xFF;
        }
        return sum & 0xFFFF;
    }
}
