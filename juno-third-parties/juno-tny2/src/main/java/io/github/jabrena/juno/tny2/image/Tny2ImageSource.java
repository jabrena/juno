package io.github.jabrena.juno.tny2.image;

import io.github.jabrena.juno.tny2.Tny2Config;
import io.github.jabrena.juno.tny2.Tny2Reader;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Objects;

/**
 * Generates the flash-resident Java image of a TNY2 file: the file's bytes split into 4 KiB {@code static final}
 * tables, one nested class each so no class initializer outgrows the JVM's 64 KiB method limit, behind a
 * zero-allocation {@code byteAt}. A board program copies it into PSRAM before the engine runs it.
 */
public final class Tny2ImageSource {
    public static final String PACKAGE = "io.github.jabrena.juno.thirdparty.tny2";
    public static final String CLASS_NAME = "Tny2ModelImage";
    private static final int CHUNK_SIZE = 4096;
    private static final int VALUES_PER_LINE = 16;

    private final byte[] bytes;
    private final Tny2Config config;

    /** Validates {@code bytes} as a complete TNY2 file before anything is generated. */
    public Tny2ImageSource(byte[] bytes) {
        this.config = new Tny2Reader().read(bytes).config();
        this.bytes = bytes.clone();
    }

    /** Writes the generated source, creating its parent directories when needed. */
    public void write(Path output) throws IOException {
        Path absolute = output.toAbsolutePath();
        Files.createDirectories(Objects.requireNonNull(absolute.getParent(), "output has no parent directory"));
        Files.writeString(absolute, source(), StandardCharsets.UTF_8);
    }

    /** Sum of the unsigned bytes modulo 2^32, which a board program can recompute after copying. */
    public int checksum() {
        int sum = 0;
        for (byte value : bytes) {
            sum += value & 0xFF;
        }
        return sum;
    }

    public String source() {
        int chunks = (bytes.length + CHUNK_SIZE - 1) / CHUNK_SIZE;
        StringBuilder cases = new StringBuilder();
        StringBuilder classes = new StringBuilder();
        for (int chunk = 0; chunk < chunks; chunk++) {
            cases.append("            case ").append(chunk).append(" -> Chunk").append(chunk)
                    .append(".DATA[offset];\n");
            classes.append(chunkSource(chunk));
        }
        return """
                package %s;

                /** Generated by Tny2Builder from a TNY2 model file; do not edit by hand. */
                // One switch case per 4 KiB table is the generated layout, not logic to simplify.
                @SuppressWarnings("PMD.CyclomaticComplexity")
                public final class %s {
                    public static final int LENGTH = %d;
                    public static final int WIDTH = %d;
                    public static final int LAYERS = %d;
                    public static final int HEADS = %d;
                    public static final int HIDDEN = %d;
                    public static final int CHECKSUM = %d;
                    private static final int CHUNK_SIZE = %d;

                    private %s() {
                    }

                    /** The model file's byte at {@code index}, from 0 to {@code LENGTH - 1}. */
                    public static byte byteAt(int index) {
                        int offset = index %% CHUNK_SIZE;
                        return switch (index / CHUNK_SIZE) {
                %s            default -> 0;
                        };
                    }
                %s}
                """.formatted(PACKAGE, CLASS_NAME, bytes.length, config.width(), config.layers(), config.heads(),
                config.hidden(), checksum(), CHUNK_SIZE, CLASS_NAME, cases, classes);
    }

    private String chunkSource(int chunk) {
        int from = chunk * CHUNK_SIZE;
        int to = Math.min(bytes.length, from + CHUNK_SIZE);
        StringBuilder values = new StringBuilder();
        for (int i = from; i < to; i++) {
            values.append((i - from) % VALUES_PER_LINE == 0 ? "\n                " : " ").append(bytes[i])
                    .append(',');
        }
        return """

                    private static final class Chunk%d {
                        private static final byte[] DATA = {%s
                        };
                    }
                """.formatted(chunk, values);
    }
}
