package io.github.jabrena.juno.tny2.image;

import io.github.jabrena.juno.tny2.Tny2FormatException;
import io.github.jabrena.juno.tny2.Tny2Writer;
import io.github.jabrena.juno.tny2.TrainedModels;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.lang.reflect.Method;
import java.net.URLClassLoader;
import java.nio.file.Path;
import java.util.Arrays;
import javax.tools.ToolProvider;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

@DisplayName("TNY2 image source")
class Tny2ImageSourceTest {
    @TempDir
    private Path directory;

    @Test
    @DisplayName("Generates a class that compiles and returns every model byte")
    void shouldGenerateACompilableImageOfEveryByte() throws Exception {
        // Given
        byte[] bytes = new Tny2Writer().toBytes(TrainedModels.model());
        Tny2ImageSource image = new Tny2ImageSource(bytes);
        Path source = directory.resolve("src/io/github/jabrena/juno/thirdparty/tny2/Tny2ModelImage.java");
        Path classes = directory.resolve("classes");

        // When
        image.write(source);
        int status = ToolProvider.getSystemJavaCompiler().run(null, null, null, "-d", classes.toString(),
                source.toString());

        // Then
        assertThat(status).isZero();
        try (URLClassLoader loader = new URLClassLoader(new java.net.URL[] {classes.toUri().toURL()},
                ClassLoader.getPlatformClassLoader())) {
            Class<?> generated = loader.loadClass(Tny2ImageSource.PACKAGE + "." + Tny2ImageSource.CLASS_NAME);
            Method byteAt = generated.getMethod("byteAt", int.class);
            byte[] read = new byte[bytes.length];
            int sum = 0;
            for (int i = 0; i < read.length; i++) {
                read[i] = (byte) byteAt.invoke(null, i);
                sum += read[i] & 0xFF;
            }
            assertThat(read).isEqualTo(bytes);
            assertThat(generated.getField("LENGTH").getInt(null)).isEqualTo(bytes.length);
            assertThat(generated.getField("WIDTH").getInt(null)).isEqualTo(32);
            assertThat(generated.getField("LAYERS").getInt(null)).isEqualTo(1);
            assertThat(generated.getField("HEADS").getInt(null)).isEqualTo(2);
            assertThat(generated.getField("HIDDEN").getInt(null)).isEqualTo(64);
            assertThat(generated.getField("CHECKSUM").getInt(null)).isEqualTo(sum).isEqualTo(image.checksum());
            assertThat((byte) byteAt.invoke(null, bytes.length + 4096)).isZero();
        }
    }

    @Test
    @DisplayName("Splits the bytes into 4 KiB tables, one class each")
    void shouldSplitTheBytesIntoChunkClasses() {
        // Given
        byte[] bytes = new Tny2Writer().toBytes(TrainedModels.model());

        // When
        String source = new Tny2ImageSource(bytes).source();

        // Then
        int chunks = (bytes.length + 4095) / 4096;
        assertThat(source).contains("case 0 -> Chunk0.DATA[offset];")
                .contains("case %d -> Chunk%d.DATA[offset];".formatted(chunks - 1, chunks - 1))
                .doesNotContain("Chunk" + chunks + ".")
                .contains("Generated by Tny2Builder", "private static final int CHUNK_SIZE = 4096;");
    }

    @Test
    @DisplayName("Copies its input and rejects bytes that are not a TNY2 model")
    void shouldCopyItsInputAndRejectInvalidModels() {
        // Given
        byte[] bytes = new Tny2Writer().toBytes(TrainedModels.model());
        Tny2ImageSource image = new Tny2ImageSource(bytes);
        int checksum = image.checksum();

        // When
        Arrays.fill(bytes, (byte) 0);

        // Then
        assertThat(image.checksum()).isEqualTo(checksum);
        assertThatThrownBy(() -> new Tny2ImageSource(new byte[] {1, 2, 3})).isInstanceOf(Tny2FormatException.class);
    }
}
