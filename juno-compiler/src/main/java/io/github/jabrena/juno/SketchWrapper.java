package io.github.jabrena.juno;

import java.nio.file.Path;

/**
 * The {@code .ino} file that turns generated assembly into an Arduino sketch: its {@code setup()} calls the
 * program's entry point, which never returns, so {@code loop()} stays empty.
 *
 * @param entryPointSymbol the assembly symbol of the program's {@code main}
 * @param mainLauncher the shim function that runs the entry point on a task of its own, or {@code ""} when
 *     {@code setup()} calls it directly
 */
public record SketchWrapper(String entryPointSymbol, String mainLauncher) {
    public SketchWrapper(String entryPointSymbol) {
        this(entryPointSymbol, "");
    }

    public String source() {
        if (!mainLauncher.isEmpty()) {
            return """
                    // Generated by Juno. Do not edit.
                    extern "C" void %1$s();
                    extern "C" void %2$s(void (*entry)());

                    void setup() {
                      %2$s(%1$s);
                    }

                    void loop() {
                    }
                    """.formatted(entryPointSymbol, mainLauncher);
        }
        return """
                // Generated by Juno. Do not edit.
                extern "C" void %1$s();

                void setup() {
                  %1$s();
                }

                void loop() {
                }
                """.formatted(entryPointSymbol);
    }

    public void writeTo(Path output) {
        new GeneratedFiles().write(output, source(), "sketch wrapper");
    }
}
